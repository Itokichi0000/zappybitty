export const translations: Record<Locale, Record<TranslationKey, string>> = { ja, en };

export type TranslationParams = Record<string, string | number>;

/** "3 bitty": the in-game point unit. */
export function formatBits(locale: Locale, n: number): string {
  return translate(locale, "bitsAmount", { n: n.toLocaleString("en-US") });
}

/** Looks up a string and substitutes {placeholders}. */
export function translate(locale: Locale, key: TranslationKey, params?: TranslationParams): string {
  const template = translations[locale]?.[key] ?? translations.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}
